/// 非白名单环境键必须在创建任何子目录或运行命令前失败。
#[test]
fn rejects_environment_outside_explicit_allowlist() {
    let workspace = TestRoot::new("workspace-env-reject");
    let scratch = TestRoot::new("scratch-env-reject");
    let mut config = worker_config(&scratch);
    config
        .environment
        .insert("SECRET_TOKEN".to_string(), "secret".to_string());
    let (inspector, calls) = inspector();
    let mut worker = PluginBuilderWorker::new(config, RecordingRunner::default(), inspector);
    assert!(matches!(
        worker.build(build_request(dependency_plan(&workspace))),
        Err(PluginBuilderWorkerError::InvalidConfig(_))
    ));
    assert!(worker.runner().requests.is_empty());
    assert_eq!(calls.get(), 0);
}

/// 真实 Runner 必须在固定时限后终止并 wait，而不是无限等待子进程。
#[test]
fn real_runner_kills_and_waits_after_timeout() {
    let shell = PathBuf::from("/bin/sh");
    if !shell.exists() {
        return;
    }
    let mut runner = RealProcessRunner;
    let request = ProcessRequest {
        program: shell,
        arguments: vec!["-c".to_string(), "sleep 5".to_string()],
        current_directory: std::env::temp_dir(),
        clear_environment: true,
        environment: BTreeMap::new(),
        timeout: Duration::from_millis(30),
    };
    let started = Instant::now();
    assert!(runner.run(&request).is_err());
    assert!(
        started.elapsed() < Duration::from_secs(2),
        "超时进程应被及时终止并回收"
    );
}

/// 真实 Worker 必须用清空环境后的固定 Cargo 流水线完成两次离线构建并生成同摘要 WASM。
#[test]
fn real_worker_builds_reproducible_wasm_in_isolated_directories() {
    let sysroot = std::process::Command::new("rustc")
        .args(["--print", "sysroot"])
        .output()
        .expect("读取当前 Rust sysroot")
        .stdout;
    let sysroot = PathBuf::from(
        String::from_utf8(sysroot)
            .expect("Rust sysroot 应为 UTF-8")
            .trim(),
    );
    let bin = sysroot.join("bin");
    let cargo = bin.join("cargo");
    let rustc = bin.join("rustc");
    let rustdoc = bin.join("rustdoc");
    for executable in [&cargo, &rustc, &rustdoc] {
        let metadata = fs::symlink_metadata(executable).expect("工具链可执行文件应存在");
        assert!(
            metadata.is_file() && !metadata.file_type().is_symlink(),
            "真实 Worker 只接受非符号链接工具链文件"
        );
    }

    let workspace = TestRoot::new("workspace-real-build");
    let scratch = TestRoot::new("scratch-real-build");
    let plan = dependency_plan(&workspace);
    let (inspector, calls) = inspector();
    let mut worker = PluginBuilderWorker::new(
        PluginBuilderWorkerConfig {
            cargo_executable: cargo,
            scratch_parent: scratch.0.clone(),
            builder_revision: digest(b"real-builder-v1"),
            environment: BTreeMap::from([
                ("PATH".into(), format!("{}:/usr/bin:/bin", bin.display())),
                ("RUSTC".into(), rustc.display().to_string()),
                ("RUSTDOC".into(), rustdoc.display().to_string()),
                ("SOURCE_DATE_EPOCH".into(), "1".into()),
            ]),
            step_timeout: Duration::from_secs(120),
        },
        RealProcessRunner,
        inspector,
    );
    let result = worker
        .build(build_request(plan))
        .expect("真实隔离 Worker 应完成两次固定流水线");
    assert!(result.attestation.reproducible);
    assert!(result.component_bytes.starts_with(b"\0asm"));
    assert_eq!(result.steps.len(), 10);
    assert_eq!(calls.get(), 1);
}
